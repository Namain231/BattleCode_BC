"""Generate viper_v7/maps_data.hpp from the bundled .map files.

The bot uses these only as a hint: it identifies the map from its spawn and
first view, keeps validating every edge it sees, and drops the hint the moment
anything disagrees.

Usage: python tools/gen_maps.py [maps_dir] [out_path]
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
maps_dir = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "maps"
out_path = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "viper_v7" / "maps_data.hpp"


def parse(path):
    w = h = 0
    tiles, edges, dragons = [], [], []
    for line in path.read_text().splitlines():
        p = line.split()
        if not p:
            continue
        if p[0] == "MAP":
            w, h = int(p[1]), int(p[2])
        elif p[0] == "TILE":
            tiles.append(tuple(int(v) for v in p[1:5]))
        elif p[0] == "EDGE":
            edges.append(tuple(int(v) for v in p[1:4]))
        elif p[0] == "DRAGON":
            team, n = int(p[1]), int(p[2])
            coords = [int(v) for v in p[3:3 + 2 * n]]
            dragons.append((team, [(coords[2 * i], coords[2 * i + 1]) for i in range(n)]))
    return w, h, tiles, edges, dragons


def main():
    out = ["// Generated by tools/gen_maps.py -- do not edit by hand.",
           "#pragma once", "#include <cstdint>", "",
           "struct KnownMap {",
           "    const char* name;",
           "    int w, h;",
           "    int n_edges;",
           "    const int* edges;      // quads: normalised cell, dir (0=N or 3=W), kind (1 kelp, 2 portal), portal id",
           "    const uint16_t* gaps;  // per cell: min, max (max 0 = never spawns)",
           "    int n_spawn;",
           "    const int* spawns;     // per dragon: team, count, then cells head first",
           "    int spawn_len;",
           "};", ""]
    names = []
    for idx, path in enumerate(sorted(maps_dir.glob("*.map"))):
        w, h, tiles, edges, dragons = parse(path)
        gaps = [0] * (2 * w * h)
        for x, y, lo, hi in tiles:
            c = y * w + x
            gaps[2 * c], gaps[2 * c + 1] = lo, hi
        norm = []
        for index, kind, pid in edges:
            if kind == 0:
                continue
            r, col = divmod(index, w + 1)
            if r % 2 == 0:
                x, y, d = col % w, (r // 2) % h, 0  # north edge of (x, y)
            else:
                x, y, d = col % w, ((r - 1) // 2) % h, 3  # west edge of (x, y)
            norm += [y * w + x, d, kind, pid]
        spawn = []
        for team, cells in dragons:
            spawn += [team, len(cells)] + [y * w + x for x, y in cells]
        tag = f"m{idx}"
        out.append(f"// {path.name}")
        out.append(f"static const int {tag}_edges[] = {{{','.join(map(str, norm)) or '0'}}};")
        out.append(f"static const uint16_t {tag}_gaps[] = {{{','.join(map(str, gaps))}}};")
        out.append(f"static const int {tag}_spawns[] = {{{','.join(map(str, spawn))}}};")
        names.append(f'    {{"{path.stem}", {w}, {h}, {len(norm) // 4}, {tag}_edges, {tag}_gaps, '
                     f'{len(dragons)}, {tag}_spawns, {len(spawn)}}},')
    out.append("")
    out.append("static const KnownMap KNOWN_MAPS[] = {")
    out += names
    out.append("};")
    out.append(f"static const int N_KNOWN_MAPS = {len(names)};")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(out) + "\n")
    print(f"wrote {out_path} ({len(names)} maps, {out_path.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
