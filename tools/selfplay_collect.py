"""Self-play data collection for imitation learning of the CURRENT S4.7 policy, gossip and
crowding/pheromone repulsion included.

Why: ml/build_dataset.py's existing 2.34M-sample dataset is built from OTHER teams' public
replays -- it can only ever teach a network to imitate what is visible in those replays. Our own
gossip messages and crowding field are internal to our own process and never appear in anyone
else's game log, so the only way a network can ever learn from (or around) them is training data
generated by actually running S4.7 and keeping the replays. This also avoids ml/results.md's
already-observed "old versions teach old habits" problem: retuning gossip/crowding after training
would silently invalidate a dataset built from an older policy.

    python tools/selfplay_collect.py --out ladder/selfplay_s47 --games 400 -j 3
    python tools/selfplay_collect.py --out ladder/selfplay_s47 --games 200 --vs-v712 0.5 -j 3

Runs S4.7-vs-S4.7 self-play by default (every game teaches the current policy, win or lose, since
both sides are it); --vs-v712 <fraction> mixes in that fraction of games as S4.7-vs-V7.12 instead
(only S4.7's *winning* games there are usable -- ml/build_dataset.py already filters for that).
Maps are drawn from the live pool plus, if --maps-gen is given, tools/gen_random_maps.py's 300
unseen layouts (guide/6_ideas_to_try.md's generalisation point: don't only ever learn the 10 named
mazes). Meant to run for hours unattended: progress is written to <out>/index.json after every
game, so a kill/restart loses at most one game, and it can resume (skips games already recorded
for a given job id).

Next step once this has run a while: `python ml/build_dataset.py --index <out>/index.json --out
ml/data_s47`, then `ml/train.py` / `ml/export_cpp.py` exactly as guide 5 describes.
"""
import argparse
import concurrent.futures as cf
import json
import pathlib
import random
import subprocess
import sys
import threading

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import tourney  # noqa: E402  (reuses prepare() so both bots build to wasm exactly once)

ROOT = pathlib.Path(__file__).resolve().parents[1]
LIVE = ["portals", "slithery_fight", "schooltime", "trophy", "queen_of_spades", "default",
        "dilemma", "autarky", "devil", "trauma", "arena", "Colosseum", "default_small",
        "stronghold"]


def run_one(map_name, a_path, b_path, seed, replay_path):
    mp = pathlib.Path(map_name if map_name.endswith(".map") else f"{map_name}.map")
    mp = mp if "/" in map_name or "\\" in map_name else ROOT / "maps" / mp
    cmd = ["unswbc", "run", str(ROOT / mp if not mp.is_absolute() else mp), a_path, b_path,
           "--sandbox", "--seed", str(seed), "-o", str(replay_path)]
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, errors="replace", timeout=280).stdout
    except subprocess.TimeoutExpired:
        return None
    m = tourney.RESULT.search(out)
    if not m:
        return None  # draw or error: not useful as a "winner" imitation sample
    return m.group(1)  # "A" or "B"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--games", type=int, default=200)
    ap.add_argument("--bot", default="viper_vS4.7")
    ap.add_argument("--opponent", default="viper_nn")  # Y.7.12-nn.1, the actual current champion
    ap.add_argument("--vs-v712", type=float, default=0.0, help="fraction of games vs the opponent instead of self-play")
    ap.add_argument("--maps-gen", action="store_true", help="also draw from maps_gen/ (300 random maps)")
    ap.add_argument("-j", type=int, default=3)
    a = ap.parse_args()

    out_dir = ROOT / a.out
    out_dir.mkdir(parents=True, exist_ok=True)
    replay_dir = out_dir / "replays"
    replay_dir.mkdir(exist_ok=True)
    index_path = out_dir / "index.json"
    index = json.loads(index_path.read_text(encoding="utf-8")) if index_path.exists() else []
    done_ids = {e["game"] for e in index}
    lock = threading.Lock()

    print("building bots to wasm...", flush=True)
    bot_path = tourney.prepare(a.bot)
    opp_path = tourney.prepare(a.opponent)

    maps = list(LIVE)
    if a.maps_gen:
        gen = sorted((ROOT / "maps_gen").glob("gen_*.map"))
        maps += [str(p) for p in gen]
    if not maps:
        print("no maps found", file=sys.stderr)
        return

    def job(i):
        if i in done_ids:
            return
        rnd = random.Random(i)
        map_name = rnd.choice(maps)
        seed = rnd.randint(1, 2**31 - 1)
        vs_opponent = rnd.random() < a.vs_v712
        # alternate which side is S4.7 so both A/B positions are represented
        s47_is_a = i % 2 == 0
        a_path = bot_path if s47_is_a else (opp_path if vs_opponent else bot_path)
        b_path = (opp_path if vs_opponent else bot_path) if s47_is_a else bot_path
        replay_path = replay_dir / f"{i}.replay"
        winner = run_one(map_name, a_path, b_path, seed, replay_path)
        entry = {
            "game": i,
            "path": str(replay_path.relative_to(out_dir)) if replay_path.exists() else None,
            "side": "A" if s47_is_a else "B",
            "winner": winner,
            "map": map_name,
            "vs_v712": vs_opponent,
        }
        with lock:
            index.append(entry)
            index_path.write_text(json.dumps(index, indent=1), encoding="utf-8")
        tag = "WIN" if winner == entry["side"] else ("LOSS" if winner else "DRAW/ERR")
        print(f"[{len(index)}/{a.games}] game {i} {map_name} vs_v712={vs_opponent} -> {tag}", flush=True)

    todo = [i for i in range(a.games) if i not in done_ids]
    print(f"{len(todo)} games to run ({len(done_ids)} already done)", flush=True)
    with cf.ThreadPoolExecutor(a.j) as ex:
        list(ex.map(job, todo))
    print("done", flush=True)


if __name__ == "__main__":
    main()
