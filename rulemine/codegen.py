"""Exported model JSON -> a C++ header gP includes. Pure functions over a feature array; no runtime loading.

The feature order is the model's own list; the header also emits the names so the bot fills them by name.
Generated code must agree with learn.predict() on every input (tests/test_learn_codegen.py compiles and checks it).
"""
import hashlib
import json


def _ident(s):
    return "".join(ch if ch.isalnum() else "_" for ch in s)


def header(models, stamp=""):
    """models: {decision_name: exported model dict}. Returns the header text."""
    out = ["// GENERATED by rulemine.codegen -- do not edit by hand. " + stamp,
           "#pragma once", "#include <cmath>", "", "namespace rm {", ""]
    for name, m in models.items():
        n = _ident(name)
        feats = m["features"]
        out.append(f"// {name}: {m['type']} over {len(feats)} features")
        out.append(f"#define RM_HAS_{n} 1")
        out.append(f"constexpr int {n}_NF = {len(feats)};")
        out.append(f"constexpr const char* {n}_FEATURES[{len(feats)}] = {{" +
                   ", ".join(f'"{f}"' for f in feats) + "};")
        if m["type"] == "logistic":
            ws = ", ".join(repr(float(w)) for w in m["weights"])
            out += [f"constexpr double {n}_W[{len(feats)}] = {{{ws}}};",
                    f"inline double {n}_prob(const double* f) {{",
                    f"    double z = {float(m['bias'])!r};",
                    f"    for (int i = 0; i < {n}_NF; i++) z += {n}_W[i] * f[i];",
                    "    return 1.0 / (1.0 + std::exp(-z));", "}"]
        elif m["type"] == "tree":
            out.append(f"inline double {n}_prob(const double* f) {{")
            nodes = m["nodes"]

            def emit(k, ind):
                nd = nodes[k]
                pad = "    " * ind
                if nd["left"] < 0:
                    out.append(f"{pad}return {nd['p']!r};  // n={nd['n']}")
                    return
                out.append(f"{pad}if (f[{nd['feature']}] <= {nd['threshold']!r}) {{  // {feats[nd['feature']]}")
                emit(nd["left"], ind + 1)
                out.append(f"{pad}}} else {{")
                emit(nd["right"], ind + 1)
                out.append(f"{pad}}}")
            emit(0, 1)
            out.append("}")
        elif m["type"] == "clogit":
            ws = ", ".join(repr(float(w)) for w in m["weights"])
            out += [f"constexpr double {n}_W[{len(feats)}] = {{{ws}}};",
                    f"inline double {n}_utility(const double* c) {{",
                    "    double u = 0;",
                    f"    for (int i = 0; i < {n}_NF; i++) u += {n}_W[i] * c[i];",
                    "    return u;", "}"]
        else:
            raise ValueError(m["type"])
        if "threshold" in m:
            out.append(f"constexpr double {n}_THRESHOLD = {float(m['threshold'])!r};")
        out.append("")
    out += ["}  // namespace rm", ""]
    return "\n".join(out)


def from_results(result_paths, out_path):
    models = {}
    data_stamps = []
    digest = hashlib.sha256()
    for path in result_paths:
        res = json.load(open(path))
        name = res.get("decision") or path.rsplit("/", 1)[-1].split(".")[0]
        m = res["model"] if "model" in res else res
        if "threshold" in res:
            m = dict(m, threshold=res["threshold"])
        models[name] = m
        digest.update(open(path, "rb").read())
        if res.get("data"):
            data_stamps.append(f"{name}<-{res['data']['path']}@{res['data']['sha256']}")
    text = header(models, stamp=f"models sha256:{digest.hexdigest()[:12]} data " + (", ".join(data_stamps) or "?"))
    open(out_path, "w").write(text)
    return text
