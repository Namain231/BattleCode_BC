"""Export a trained policy to a C++ header for the bot, with a built-in test vector.

    python ml/export_cpp.py ml/models/policy_pilot.pt viper_nn/policy_weights.hpp [--data ml/data_pilot]

The header holds the weights (float) and one validation sample with the logits PyTorch computed for it, so the bot
can check its own forward pass inside the judge's sandbox (NN_SELFTEST).
"""
import argparse
import glob
import os
import sys

import numpy as np
import torch

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from train import Policy  # noqa: E402


def arr(name, t):
    a = t.detach().cpu().numpy().astype(np.float32).ravel()
    def lit(v):   # a valid C++ float literal: "1f" / "0f" are not, "1.f" / "0.f" are
        t = f"{v:.7g}"
        return (t if any(ch in t for ch in ".eEn") else t + ".") + "f"
    body = ",".join(lit(v) for v in a)
    return f"static const float {name}[{a.size}] = {{{body}}};\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("model"); ap.add_argument("out")
    ap.add_argument("--data", default="ml/data_pilot")
    a = ap.parse_args()
    ck = torch.load(a.model, map_location="cpu")
    nsc, ch, hid, nout = ck.get("scalars", 3), ck.get("channels", 32), ck.get("hidden", 64), ck.get("classes", 6)
    npl = ck.get("planes", 16)
    m = Policy(planes=npl, scalars=nsc, ch=ch, hidden=hid, classes=nout); m.load_state_dict(ck["state_dict"]); m.eval()
    sd = m.state_dict()
    d = np.load(sorted(glob.glob(os.path.join(a.data, "shard_*.npz")))[0])
    i = 123
    planes = torch.from_numpy(d["planes"][i:i + 1]).float() / 255
    sv = np.zeros((1, nsc), np.float32)   # test input: the sample's scalars, zero-padded (e.g. team one-hot)
    k = min(nsc, d["scalars"].shape[1], 3 if ck.get("team_cond") or nsc > 6 else nsc)
    sv[0, :k] = d["scalars"][i, :k]
    scal = torch.from_numpy(sv)
    with torch.no_grad():
        logits = m(planes, scal)[0]
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w") as f:
        f.write("// generated by ml/export_cpp.py from " + os.path.basename(a.model) + "\n#pragma once\n")
        f.write(f"#define NN_NSCAL {nsc}\n#define NN_CH {ch}\n#define NN_HID {hid}\n#define NN_NOUT {nout}\n"
                f"#define NN_NPLANES {npl}\n")
        for k in ("c1.weight", "c1.bias", "c2.weight", "c2.bias", "c3.weight", "c3.bias",
                  "fc.weight", "fc.bias", "out.weight", "out.bias"):
            f.write(arr("NN_" + k.replace(".", "_").upper(), sd[k]))
        f.write(f"static const unsigned char NN_TEST_PLANES[{npl * 15 * 15}] = {{"
                + ",".join(str(int(v)) for v in d["planes"][i].ravel()) + "};\n")
        f.write(arr("NN_TEST_SCALARS", scal[0]))
        f.write(arr("NN_TEST_LOGITS", logits))
    print(a.out, f"{os.path.getsize(a.out) / 1e6:.2f} MB; test logits", [round(float(x), 4) for x in logits])


if __name__ == "__main__":
    main()
